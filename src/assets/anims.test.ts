import assert from "node:assert/strict";
import { execFileSync } from "node:child_process";
import { existsSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { describe, it } from "node:test";
import { fileURLToPath } from "node:url";
import { snapToArtPixels } from "../core/art-grid.ts";
import { evaluateCurve } from "../core/anim/hermite.ts";
import { WORLD_SPRITES, type WorldSpriteLabel } from "../game/scene/positions.ts";
import { CLIPS, TARGETS, type ClipId } from "./anims.ts";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "../..");
// The Unity project's checkout: UNITY_CHECKOUT, or next to this repository's parent as in the coordinator's setup.
const CHECKOUT = process.env.UNITY_CHECKOUT ?? resolve(ROOT, "../stefanhacks/after-the-waves-crash");
const HAS_CHECKOUT = existsSync(join(CHECKOUT, "Assets/Graphics/Animations"));

const firstValue = (clip: ClipId, attribute: string) => {
  const curve = CLIPS[clip].curves.find((candidate) => candidate.attribute === attribute);

  assert.ok(curve !== undefined, `${clip} has ${attribute}`);

  return evaluateCurve(curve.keys, 0);
};

const staticAt = (label: WorldSpriteLabel) => {
  const sprite = WORLD_SPRITES.find((candidate) => candidate.label === label);

  assert.ok(sprite !== undefined);

  return sprite.at;
};

describe("anims.ts (generated by scripts/import-anims.mjs)", () => {
  const skip = HAS_CHECKOUT ? false : `no Unity checkout at ${CHECKOUT} (set UNITY_CHECKOUT)`;

  it("is up to date with the Unity checkout", { skip }, () => {
    const script = join(ROOT, "scripts/import-anims.mjs");
    const output = execFileSync(process.execPath, [script, CHECKOUT, "--check"], { encoding: "utf8" });

    assert.match(output, /up to date/);
  });

  it("holds the 24 clips but ChangeText, with ASCII ids, PillarsSwitch marked unused", () => {
    const clips = Object.values(CLIPS);

    assert.equal(clips.length, 23);
    assert.ok(clips.every((clip) => (clip.name as string) !== "ChangeText"));
    assert.equal(CLIPS.seaAnimTres.name, "SeaAnimTrês");
    assert.equal(CLIPS.pillarsSwitch.unused, true);
    assert.ok(Object.keys(CLIPS).every((id) => /^[a-z][A-Za-z0-9]*$/.test(id)));
    // 04: 20 curve clips (19 once ChangeText is dropped), 3 event-only, PillarsSwitch only swaps sprites.
    assert.equal(clips.filter((clip) => clip.curves.length > 0).length, 19);
    const eventOnly = clips.filter((clip) => clip.curves.length === 0 && clip.events.length > 0);

    assert.deepEqual(eventOnly.map((clip) => clip.name), ["Fim", "Inicio", "Troca"]);
  });

  it("plays the legacy clips once, whatever their m_LoopTime", () => {
    assert.equal(CLIPS.flash.legacy, true);
    assert.equal(CLIPS.flash.loop, false);
    assert.deepEqual(CLIPS.flash.events, [{ time: 0.25, functionName: "DoingFlash" }]);
  });
});

// The clips' first keys, converted through Main.unity's parent chains, against the M2 static positions (positions.ts),
// both on the art grid as `addArtSprite` places them.
describe("anims.ts: first keys against the M2 positions", () => {
  const snapped = (x: number, y: number, size: { width: number; height: number }) => ({
    x: snapToArtPixels(x, 0.5, size.width),
    y: snapToArtPixels(y, 0.5, size.height),
  });

  it("puts the boat where M2 does (Barco: local (0, 0) under Barco Inteiro, 309.5 → 310)", () => {
    const { parentOrigin } = TARGETS["Stage/Barco Inteiro/InteiroSprite"];
    const x = parentOrigin.x + firstValue("barco", "m_LocalPosition.x");
    const y = parentOrigin.y - firstValue("barco", "m_LocalPosition.y");

    assert.deepEqual(snapped(x, y, { width: 32, height: 32 }), staticAt("boat"));
  });

  it("puts the clouds where M2 does (Clouds moves Sky; Clouds1 sits 64 below its pivot)", () => {
    const sky = TARGETS["Stage/Sky"];
    const clouds1 = sky.sprites[0];

    assert.equal(clouds1.name, "Clouds1");
    const x = sky.anchorOrigin.x + firstValue("clouds", "m_AnchoredPosition.x") + clouds1.offset.x;

    assert.deepEqual({ x, y: sky.at.y + clouds1.offset.y }, staticAt("clouds"));
  });

  it("puts the sea strips where WORLD_SPRITES starts them: the clips' first keys", () => {
    const strips = [
      ["Stage/Sea/Back", "seaAnimTres", "seaB"],
      ["Stage/Sea/Mid", "seaAnimDois", "seaM"],
      ["Stage/Sea/Front", "seaAnim", "seaF"],
    ] as const;

    for (const [path, clip, label] of strips) {
      const { anchorOrigin } = TARGETS[path];
      const x = anchorOrigin.x + firstValue(clip, "m_AnchoredPosition.x");
      const y = anchorOrigin.y - firstValue(clip, "m_AnchoredPosition.y");

      assert.equal(y, staticAt(label).y, label);
      // Every sea clip starts at x −25 and slides to −57: one 32 px period of the strip's art, so the loop is seamless.
      // M2 kept the placeholder's centred 250; M4's table starts the strips at the clip's 225.
      assert.equal(x, 225, label);
      assert.equal(staticAt(label).x, x, label);
    }
  });

  it("puts the broken boat where M2 does (local (0, −35) under Barco Quebrado)", () => {
    const { parentOrigin } = TARGETS["Stage/Barco Quebrado/QuebradoSprite"];
    const x = parentOrigin.x + firstValue("barcoQuebradoJogadoCima", "m_LocalPosition.x");
    const y = parentOrigin.y - firstValue("barcoQuebradoJogadoCima", "m_LocalPosition.y");

    assert.deepEqual(snapped(x, y, { width: 42, height: 42 }), staticAt("broken-boat"));
  });

  it("starts the kraken body off its Main.unity place: FadeKrakenA moves it while it fades in", () => {
    const { parentOrigin, at } = TARGETS["Stage/Monster/Body"];
    const x = parentOrigin.x + firstValue("fadeKrakenA", "m_LocalPosition.x");
    const y = parentOrigin.y - firstValue("fadeKrakenA", "m_LocalPosition.y");

    assert.deepEqual(at, staticAt("kraken-body"));
    // (−23, 26) → (−26, 35) in Monster's space: from 3 px right and 6 px up of M2's (216, 239) to 15 px up.
    assert.deepEqual({ x, y }, { x: 219, y: 233 });
  });
});
